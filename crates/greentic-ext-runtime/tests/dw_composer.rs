//! Integration tests for `ExtensionRuntime::invoke_composer_*` methods.
//!
//! Uses a minimal hand-crafted WAT component that exports
//! `greentic:dw-composer/composer@0.1.0` with stub implementations,
//! mirroring the fixture pattern used in `runtime_load.rs` and
//! `roles_smoke.rs` — sign a describe.json, register the extension, invoke
//! the method under test.
//!
//! The WAT was derived via `wasm-tools component embed` +
//! `wasm-tools component new` against the canonical WIT in
//! `wit/extension-dw-composer.wit`. The stub implementations return static
//! in-memory JSON blobs, which is enough to prove the wasmtime dispatch path.

#[path = "support/mod.rs"]
mod support;

use std::path::PathBuf;

use greentic_ext_runtime::{DiscoveryPaths, ExtensionRuntime, RuntimeConfig, RuntimeError};
use greentic_extension_sdk_contract::ExtensionKind;

