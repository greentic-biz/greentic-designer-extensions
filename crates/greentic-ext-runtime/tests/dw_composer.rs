#[test]
fn invoke_composer_metadata_returns_descriptor_json() {
    let (fixture, _sk) = build_signed_composer_fixture("greentic.dw.composer.test", "0.1.0");

    // Trust root must be a temp dir: the default is the developer's real
    // ~/.greentic, and the fixture is signed with a fresh key per call.
    let trust = tempfile::TempDir::new().expect("temp trust root");
    let config = RuntimeConfig::from_paths(DiscoveryPaths::new(PathBuf::from("/dev/null")))
        .with_trust_root(trust.path().to_path_buf());
    let mut runtime = ExtensionRuntime::new(config).expect("new runtime");
    runtime
        .register_loaded_from_dir(fixture.root())
        .expect("register composer extension");

    let metadata_json = runtime
        .invoke_composer_metadata("greentic.dw.composer.test")
        .expect("invoke_composer_metadata should succeed");

    // The stub returns {"id":"test","name":"Test Composer"}.
    let parsed: serde_json::Value =
        serde_json::from_str(&metadata_json).expect("metadata should be valid JSON");
    assert_eq!(parsed["id"], "test", "expected id='test', got: {parsed:#}");
    assert_eq!(
        parsed["name"], "Test Composer",
        "expected name='Test Composer', got: {parsed:#}"
    );
}

#[test]
fn invoke_composer_compose_returns_ok_manifest_json() {
    let (fixture, _sk) =
        build_signed_composer_fixture("greentic.dw.composer.compose-test", "0.1.0");

    // Trust root must be a temp dir: the default is the developer's real
    // ~/.greentic, and the fixture is signed with a fresh key per call.
    let trust = tempfile::TempDir::new().expect("temp trust root");
    let config = RuntimeConfig::from_paths(DiscoveryPaths::new(PathBuf::from("/dev/null")))
        .with_trust_root(trust.path().to_path_buf());
    let mut runtime = ExtensionRuntime::new(config).expect("new runtime");
    runtime
        .register_loaded_from_dir(fixture.root())
        .expect("register composer extension");

    let result = runtime
        .invoke_composer_compose(
            "greentic.dw.composer.compose-test",
            r#"{"intent":"open-savings-account","currency":"EUR"}"#,
        )
        .expect("invoke_composer_compose host call should succeed");

    // The stub always returns Ok(metadata_json).
    let manifest_json = result.expect("stub compose should return Ok");
    assert!(
        !manifest_json.is_empty(),
        "returned manifest JSON should not be empty"
    );
    // Verify it's parseable JSON.
    serde_json::from_str::<serde_json::Value>(&manifest_json)
        .expect("compose Ok value should be valid JSON");
}
